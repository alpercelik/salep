    [Fact]
    public void Fragment_errors_are_configuration_diagnostics_and_do_not_publish_partial_output()
    {
        var root = Path.Combine(Path.GetTempPath(), "salep-fragment-error-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(root);
        try
        {
            File.WriteAllText(Path.Combine(root, "schema.graphql"), "type Query { hello: String! }");
            File.WriteAllText(Path.Combine(root, "operation.graphql"), "query Hello { hello }");
            File.WriteAllText(Path.Combine(root, "members.scriban-cs"), "// valid hook\n");
            File.WriteAllText(Path.Combine(root, "salep.json"), """
                {"version":1,"kind":"client","schema":"schema.graphql","operations":"operation.graphql","output":"Generated","templates":{"client.members":"members.scriban-cs"}}
                """);
            ScribanGenerator.Generate(new("salep.json", root));
            var previous = Directory.GetFiles(Path.Combine(root, "Generated")).ToDictionary(file => Path.GetFileName(file)!, File.ReadAllText);
            File.WriteAllText(Path.Combine(root, "members.scriban-cs"), "{{ if }}");
            var error = Assert.Throws<ScribanConfigurationException>(() => ScribanGenerator.Generate(new("salep.json", root)));
            Assert.Equal("SALEPS1006", error.Diagnostic.Code);
            Assert.Contains("client.members", error.Diagnostic.Message, StringComparison.Ordinal);
            foreach (var file in previous) Assert.Equal(file.Value, File.ReadAllText(Path.Combine(root, "Generated", file.Key!)));
        }
        finally { Directory.Delete(root, true); }
    }

    [Fact]
    public void Export_keys_and_configuration_schema_stay_synchronized()
    {
        var catalogKeys = ScribanTemplateCatalog.GetDefaultTemplateFiles().Keys.Order(StringComparer.Ordinal).ToArray();
        var apiKeys = typeof(ScribanTemplateNames).GetFields(System.Reflection.BindingFlags.Public | System.Reflection.BindingFlags.Static)
            .Select(field => (string)field.GetRawConstantValue()!).Order(StringComparer.Ordinal).ToArray();
        Assert.Equal(apiKeys, catalogKeys);
        var root = new DirectoryInfo(AppContext.BaseDirectory);
        while (root is not null && !File.Exists(Path.Combine(root.FullName, "Directory.Build.props"))) root = root.Parent;
        Assert.NotNull(root);
        using var schema = JsonDocument.Parse(File.ReadAllText(Path.Combine(root.FullName, "docs", "client-generator", "config.schema.json")));
        foreach (var kind in schema.RootElement.GetProperty("oneOf").EnumerateArray())
        {
            var keys = kind.GetProperty("properties").GetProperty("templates").GetProperty("propertyNames").GetProperty("enum")
                .EnumerateArray().Select(value => value.GetString()!).Order(StringComparer.Ordinal).ToArray();
            Assert.Equal(catalogKeys, keys);
        }
    }

    [Fact]
    public void Included_override_content_does_not_leak_between_renders()
    {
        var engine = new ScribanTemplateEngine();
        var model = new ScriptObject();
        var overrides = new Dictionary<string, string> { [ScribanTemplateNames.ClientMembers] = "first" };
        Assert.Equal("first", engine.Render("{{ include \"client.members\" }}", model, templateOverrides: overrides));
        overrides[ScribanTemplateNames.ClientMembers] = "second";
        Assert.Equal("second", engine.Render("{{ include \"client.members\" }}", model, templateOverrides: overrides));
        Assert.Equal("", engine.Render("{{ include \"client.members\" }}", model));
    }

    private static DocumentNode Parse(string source) => global::Salep.GraphQLParser.GraphQLParser.Parse(new SourceText(source.AsMemory()));
}
